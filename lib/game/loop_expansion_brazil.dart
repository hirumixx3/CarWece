List<TrackSpec> createBrazilLoopTracks() {
  final result = <TrackSpec>[];
  const oldPalettes = <String, (int, int, int)>{
    'QUARTO': (0xffffa34a, 0xff89684d, 0xff485b75),
    'GARAGEM': (0xff48d6b9, 0xff6d737b, 0xff364357),
    'ARCADE': (0xffe071d4, 0xff262945, 0xff1d2844),
    'BANHEIRO': (0xff90eee9, 0xffc8ded8, 0xff83a7b6),
    'COZINHA': (0xffffcf69, 0xffd7c8a5, 0xff9db3bd),
    'SALA': (0xffe4ab76, 0xff957357, 0xff788ca1),
  };
  for (var i = 0; i < _brazilLoopSpecs.length; i++) {
    final spec = _brazilLoopSpecs[i], room = spec.$3;
    final route = _LoopCircuit()
      ..p(-650, -710, 6)
      ..p(-650, -520, 6)
      ..loop(-650, -310, const V3(0, 0, 1), radius: 58 + i % 4 * 2.0)
      ..p(-566, -150, 6)
      ..p(-550, -10, 3);
    for (final p in _brazilLoopRoutes[i]) route.p(p.$1, p.$2);
    route.p(-530, -730, 6);
    // Alternate axis, handedness and loop sightline. Polygon layouts remain
    // different; these are not copies of the previous expansion circuits.
    final angle = (i % 4) * math.pi / 2 + [0.0, .18, -.18, .30][i ~/ 8];
    final mirror = i % 8 >= 4 ? -1.0 : 1.0;
    V3 orient(V3 p) => V3(
      (p.x * mirror * math.cos(angle) - p.z * math.sin(angle)) * .94,
      p.y,
      (p.x * mirror * math.sin(angle) + p.z * math.cos(angle)) * .94,
    );
    final biome = expansionBiomes[room];
    final palette = biome == null
        ? oldPalettes[room]!
        : (biome.accent, biome.floor, biome.horizon);
    final t = TrackSpec(
      spec.$1,
      spec.$2,
      'Loop vertical completo, curvas no piso do cenário e atalho com portão.',
      room,
      palette.$1,
      palette.$2,
      palette.$3,
      route.points.map(orient).toList(),
      width: 46,
      loopSections: [
        for (final s in route.sections)
          LoopSection(s.first, s.last, orient(s.right).unit * mirror),
      ],
    );
    if (t.outdoor) {
      populateExpansionObstacles(t, i);
    } else {
      // The vertical loop is the stunt here. Remove the generic floor ramp,
      // whose automatic midpoint can launch a car into a shortcut's closed gate.
      t.ramps.clear();
    }
    result.add(t);
  }
  return result;
}
